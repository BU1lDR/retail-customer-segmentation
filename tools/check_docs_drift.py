def check_report_builder(payload):
    src = REPORT_BUILDER.read_text(encoding="utf-8")

    # The static read below is only complete while every access is a literal. One
    # F[name] with a variable in it and this check starts quietly passing over
    # whatever that variable holds, so the assumption is asserted rather than
    # assumed.
    dynamic = re.findall(r"""\bF\[(?!['"])[^\]]{0,40}\]""", src)
    if dynamic:
        fail(
            "build_report.py now reads a fact through a variable: " + ", ".join(dynamic),
            "This check extracts literal keys only, so it can no longer claim to\n"
            "cover every fact the report reads. Either keep the accesses literal\n"
            "or teach this check to resolve them.",
        )

    keys = set(re.findall(r"""\bF\[['"]([^'"]+)['"]\]""", src))
    sections = set(re.findall(r"""\bpayload\[['"]([^'"]+)['"]\]""", src))

    absent = sorted(keys - set(payload["facts"]))
    if absent:
        fail(
            f"build_report.py reads {len(absent)} fact(s) that facts.json does not have: "
            + ", ".join(absent),
            "The report build dies on the first one. It needs the 112 MB workbook\n"
            "and a full notebook run to find that out, which is why this is here.",
        )
    absent_sections = sorted(sections - set(payload))
    if absent_sections:
        fail(
            "build_report.py reads missing top-level section(s): " + ", ".join(absent_sections)
        )
    if not absent and not absent_sections and not dynamic:
        ok(
            f"build_report.py's {len(keys)} fact(s) and {len(sections)} section(s) "
            f"all exist in facts.json"
        )


