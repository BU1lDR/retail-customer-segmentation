def main():
    if not FACTS_PATH.exists():
        sys.exit(
            f"missing {FACTS_PATH.relative_to(ROOT)} -- it is committed, so this "
            "means an incomplete checkout rather than a missing notebook run."
        )
    payload = json.loads(FACTS_PATH.read_text(encoding="utf-8"))

    print("  -- README.md against outputs/facts.json --")
    check_readme(payload["facts"])
    print()
    print("  -- tools/build_report.py against outputs/facts.json --")
    check_report_builder(payload)
    print()
    print("  -- the notebook against tools/build_notebook.py --")
    check_notebook_is_generated()
    print()
    prose, printed = notebook_text()
    report = report_text()
    print("  -- the notebook's narrative against outputs/facts.json --")
    check_anchored("the notebook's prose", prose, payload["facts"],
                   NOTEBOOK_PROSE, FIX_NOTEBOOK)
    print()
    print("  -- the committed artefacts against outputs/facts.json --")
    check_generated_from(payload, printed, report)
    check_anchored("the notebook's committed output", printed, payload["facts"],
                   NOTEBOOK_OUTPUT, FIX_OUTPUT)
    check_anchored("the committed .docx", report, payload["facts"],
                   REPORT_PROSE, FIX_REPORT)
    print()
    print("  -- the profile blurb against outputs/facts.json --")
    check_anchored("the profile blurb (.github/PROFILE.md)",
                   PROFILE.read_text(encoding="utf-8"), payload["facts"],
                   PROFILE_PROSE, FIX_PROFILE)
    print()

    if failures:
        print(f"  {failures} failure(s). The documents and the analysis disagree.")
        return 1
    print("  the documents still say what the analysis computed.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
